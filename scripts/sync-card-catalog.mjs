#!/usr/bin/env node
/**
 * Sync packages/game + API card seed from the engine catalog.
 *
 * Usage: node scripts/sync-card-catalog.mjs
 * (runs `cargo run -p ga-fire-engine --example dump_catalog`)
 */
import { spawnSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

const dump = spawnSync(
  "cargo",
  ["run", "-p", "ga-fire-engine", "--example", "dump_catalog", "--quiet"],
  { cwd: root, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
);

if (dump.status !== 0) {
  console.error(dump.stderr || dump.stdout);
  process.exit(dump.status ?? 1);
}

const payload = JSON.parse(dump.stdout);
const cards = payload.cards;
const cardDigest = String(payload.cardDigest ?? "");
if (!Array.isArray(cards) || cards.length === 0) {
  console.error("dump_catalog produced no cards");
  process.exit(1);
}
if (!cardDigest) {
  console.error("dump_catalog missing cardDigest");
  process.exit(1);
}

function tsString(value) {
  return JSON.stringify(value);
}

function formatCardObject(card, { requireAliases }) {
  const lines = [
    `  ${card.id}: {`,
    `    id: ${tsString(card.id)},`,
    `    name: ${tsString(card.name)},`,
    `    short: ${tsString(card.short)},`,
    `    kind: ${tsString(card.kind)},`,
    `    cost: ${card.cost},`,
    `    element: ${tsString(card.element)},`,
  ];
  if (card.power != null) lines.push(`    power: ${card.power},`);
  if (card.life != null) lines.push(`    life: ${card.life},`);
  if (card.stealth) lines.push(`    stealth: true,`);
  if (card.unique) lines.push(`    unique: true,`);
  if (card.assassinPowerBonus != null) {
    lines.push(`    assassinPowerBonus: ${card.assassinPowerBonus},`);
  }
  if (card.assassinStealth) lines.push(`    assassinStealth: true,`);
  if (card.automaton) lines.push(`    automaton: true,`);
  if (card.fast) lines.push(`    fast: true,`);
  if (card.floatingMemory) lines.push(`    floatingMemory: true,`);
  if (card.kindle != null) lines.push(`    kindle: ${card.kindle},`);
  if (card.prepare != null) lines.push(`    prepare: ${card.prepare},`);
  const aliases = card.aliases ?? [];
  if (requireAliases || aliases.length > 0) {
    lines.push(
      `    aliases: [${aliases.map((alias) => tsString(alias)).join(", ")}],`,
    );
  }
  lines.push(`  },`);
  return lines.join("\n");
}

const idUnion = cards.map((card) => `  | ${tsString(card.id)}`).join("\n");

const gameGenerated = `/* eslint-disable */
/** Generated by scripts/sync-card-catalog.mjs — do not edit by hand. */

/** Engine \`card_digest\` at sync time — compare to GET /version. */
export const BUNDLED_CARD_DIGEST = ${tsString(cardDigest)};

export type GeneratedCardId =
${idUnion};

type GeneratedCardDef = {
  id: GeneratedCardId;
  name: string;
  short: string;
  kind: string;
  cost: number;
  element: string;
  power?: number;
  life?: number;
  stealth?: boolean;
  unique?: boolean;
  assassinPowerBonus?: number;
  assassinStealth?: boolean;
  automaton?: boolean;
  fast?: boolean;
  floatingMemory?: boolean;
  kindle?: number;
  prepare?: number;
  aliases?: string[];
};

export const GENERATED_CARDS: Record<GeneratedCardId, GeneratedCardDef> = {
${cards.map((card) => formatCardObject(card, { requireAliases: false })).join("\n")}
};

export const GENERATED_CARD_IDS: GeneratedCardId[] = [
${cards.map((card) => `  ${tsString(card.id)},`).join("\n")}
];

export const GENERATED_FALLBACK_ALIASES: Record<string, GeneratedCardId> = {
${cards
  .flatMap((card) =>
    (card.aliases ?? []).map(
      (alias) => `  ${tsString(alias)}: ${tsString(card.id)},`,
    ),
  )
  .join("\n")}
};
`;

const seedGenerated = `/* eslint-disable */
/** Generated by scripts/sync-card-catalog.mjs — do not edit by hand. */

export const GENERATED_CARD_SEED = [
${cards
  .map((card) => {
    const parts = [
      `  {`,
      `    id: ${tsString(card.id)},`,
      `    name: ${tsString(card.name)},`,
      `    short: ${tsString(card.short)},`,
      `    kind: ${tsString(card.kind)},`,
      `    cost: ${card.cost},`,
      `    element: ${tsString(card.element)},`,
    ];
    if (card.power != null) parts.push(`    power: ${card.power},`);
    if (card.life != null) parts.push(`    life: ${card.life},`);
    if (card.stealth) parts.push(`    stealth: true,`);
    if (card.unique) parts.push(`    unique: true,`);
    if (card.assassinPowerBonus != null) {
      parts.push(`    assassinPowerBonus: ${card.assassinPowerBonus},`);
    }
    if (card.assassinStealth) parts.push(`    assassinStealth: true,`);
    if (card.automaton) parts.push(`    automaton: true,`);
    if (card.fast) parts.push(`    fast: true,`);
    if (card.floatingMemory) parts.push(`    floatingMemory: true,`);
    if (card.kindle != null) parts.push(`    kindle: ${card.kindle},`);
    if (card.prepare != null) parts.push(`    prepare: ${card.prepare},`);
    parts.push(
      `    aliases: [${(card.aliases ?? []).map((a) => tsString(a)).join(", ")}],`,
    );
    parts.push(`  },`);
    return parts.join("\n");
  })
  .join("\n")}
] as const;
`;

const gameDir = path.join(root, "packages/game/src/generated");
const apiDir = path.join(root, "apps/api/src/db/generated");
await mkdir(gameDir, { recursive: true });
await mkdir(apiDir, { recursive: true });
await writeFile(path.join(gameDir, "catalog-data.ts"), gameGenerated);
await writeFile(path.join(apiDir, "card-seed-data.ts"), seedGenerated);

console.log(
  `Synced ${cards.length} cards (digest ${cardDigest}) → packages/game/src/generated/catalog-data.ts + apps/api/src/db/generated/card-seed-data.ts`,
);
